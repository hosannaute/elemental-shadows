import type { HitHeight } from './hitboxSystem';

export type MoveId =
  | 'jab'
  | 'cross'
  | 'backfist'
  | 'high_kick'
  | 'roundhouse'
  | 'low_sweep'
  | 'weapon_slash_1'
  | 'weapon_slash_2'
  | 'weapon_thrust'
  | 'weapon_overhead'
  | 'air_kick'
  | 'air_weapon'
  | 'wakeup_sweep'
  | 'elbow_strike'
  | 'horse_kick'
  | 'back_kick'
  | 'sucker_kick'
  | 'throw_forward'
  | 'throw_back'
  | 'suplex'
  | 'magic_cast';

export interface MoveDefinition {
  id: MoveId;
  name: string;
  startup: number;
  active: number;
  recovery: number;
  damage: number;
  chipDamage: number;
  hitstun: number;
  blockstun: number;
  hitstop: number;
  knockbackX: number;
  launchY: number;
  knockdown: boolean;
  critical: boolean;
  height: HitHeight;
  hitboxOffsetX: number; // relative to fighter facing
  hitboxOffsetY: number; // relative to groundY (negative is up)
  hitboxWidth: number;
  hitboxHeight: number;
  forwardImpulse: number;
  impulseFrame: number;
  cancelWindowStart?: number;
  nextComboMove?: MoveId;
  isWeapon?: boolean;
  isThrow?: boolean;
  throwType?: 'forward' | 'back' | 'suplex';
  invulnFrames?: number;
  highEvade?: boolean; // leans/ducks under high strikes (Elbow Strike, Horse Kick)
  hitsGrounded?: boolean; // Sucker Kick hits grounded opponents
  appliesElementStatus?: boolean;
  magicGain: number;
  trailBone?: 'weapon' | 'rightFoot' | 'leftFoot' | 'rightHand' | 'leftHand';
}

